def style_for(nation: str, event: str) -> str:
    style = PERSONAS[nation]["style"]
    mood = EVENT_MOOD.get(event)
    return f"{style} {MOODS[mood]}" if mood else style


def build_catalog() -> dict[str, list[dict[str, str]]]:
    """{bucket: [{'id', 'nation', 'event', 'voice', 'model', 'style', 'voice_text'}, ...]}"""
    cat: dict[str, list[dict[str, str]]] = {}
    for event, variants in LINES.items():
        for k, q in enumerate(NATIONS):
            cat[f"{event}_{q}"] = [
                {
                    "id": f"{i + 1:02d}",
                    "nation": q,
                    "event": event,
                    "voice": VOICES[q],
                    "model": NATION_MODEL[q],
                    "style": style_for(q, event),
                    "voice_text": v[k],
                }
                for i, v in enumerate(variants)
            ]
    return cat


def caption_lines() -> dict[str, list[str]]:
    """Caption text per bucket, in variant order (the game writes the same text it plays)."""
    return {bucket: [item["voice_text"] for item in items] for bucket, items in build_catalog().items()}


if __name__ == "__main__":
    c = build_catalog()
    per_model: dict[str, int] = {}
    for items in c.values():
        for it in items:
            per_model[it["model"]] = per_model.get(it["model"], 0) + 1
    total = sum(len(v) for v in c.values())
    print(f"Buckets: {len(c)}, total clips: {total}, per model: {per_model}")
